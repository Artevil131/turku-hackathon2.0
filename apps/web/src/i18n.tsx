const dict: Record<Locale, Record<Key, string>> = { en, fi };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface I18n {
  locale: Locale;
  setLocale(l: Locale): void;
  t: T;
}

const Ctx = createContext<I18n | null>(null);

function readLocale(): Locale {
  try {
    const v = localStorage.getItem("ahead.locale");
    if (v === "fi" || v === "en") return v;
  } catch {}
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  const value = useMemo<I18n>(
    () => ({
      locale,
      setLocale(l) {
        setLocaleState(l);
        try {
          localStorage.setItem("ahead.locale", l);
        } catch {}
        document.documentElement.lang = l;
      },
      t(key, vars) {
        let s = dict[locale][key];
        for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
    }),
    [locale],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("I18nProvider missing");
  return v;
}

/** "2026-10-01" → "Oct" / "loka": the month ticks on a plate. */
export function formatMonth(iso: string, locale: Locale): string {
  const [y, m] = iso.split("-").map(Number);
  const name = new Date(Date.UTC(y ?? 1970, (m ?? 1) - 1, 1)).toLocaleDateString(locale === "fi" ? "fi-FI" : "en-GB", {
    month: "short",
    timeZone: "UTC",
  });
  return name.replace(/\.$/, "").slice(0, 4);
}

/** "2026-10-01" → "1 Oct" / "1.10.": a short date for a chart tick or a timetable cell. */
export function formatShort(iso: string, locale: Locale): string {
  const [y, m, d] = iso.split("-").map(Number);
  if (locale === "fi") return `${d}.${m}.`;
  return new Date(Date.UTC(y ?? 1970, (m ?? 1) - 1, d ?? 1)).toLocaleDateString("en-GB", {
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  });
}

export function formatDate(iso: string, locale: Locale): string {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(Date.UTC(y ?? 1970, (m ?? 1) - 1, d ?? 1)).toLocaleDateString(locale === "fi" ? "fi-FI" : "en-GB", {
    day: "numeric",
    month: "long",
    timeZone: "UTC",
  });
}
